/*
 * duckmon: embedded telemetry store. C ABI.
 *
 * Errors: every function that can fail returns a DUCKMON_* code. DUCKMON_OK is 0.
 * Treat any other value, also one this header does not list, as a failure and
 * read its message with duckmon_last_error() on the same thread.
 *
 * Data: events go in as JSON Lines text (see duckmon_store_write_events).
 * Query results come out as an Arrow IPC stream (see duckmon_store_query).
 *
 * Ownership:
 *   Every const char * argument is borrowed only during the call and must be
 *   NUL terminated UTF 8.
 *   A duckmon_store * is freed by the caller with duckmon_store_free.
 *   A duckmon_bytes is freed by the caller with duckmon_bytes_free.
 *   Never free anything duckmon hands out with free().
 *   Output arguments are reset to NULL or {NULL, 0} at the start of a call and
 *   are written only on success.
 *
 * Threads:
 *   Every function may be called from any thread.
 *   One duckmon_store * may be used by many threads at once. Write, flush and
 *   query run at the same time.
 *   duckmon_store_close may race with other calls on the same handle. They
 *   either finish first or return DUCKMON_ERROR_CLOSED.
 *   duckmon_store_free must not run at the same time as any other call on the
 *   same handle, and the handle must not be used afterwards.
 *   A NULL pointer gives DUCKMON_ERROR_INVALID_ARGUMENT. A dangling pointer,
 *   or one duckmon did not create, is undefined behavior.
 *   Using duckmon across fork() is not supported.
 *
 * Linking: the shared library needs nothing else. With the static library
 * libduckmon_ffi.a, also link the system libraries that
 *   cargo rustc -p duckmon-ffi --release --crate-type staticlib -- --print native-static-libs
 * lists, for example on macOS: -lc++ -lc -lm -liconv -framework CoreFoundation.
 *
 * Versions: DUCKMON_ABI_VERSION goes up only when the meaning of an existing
 * function, code or JSON key changes. Compare it with duckmon_abi_version()
 * when the library loads.
 */

